fn look_up(first: u8, second: u8) -> Option<char> {
    let (_, _, c) = COMPOSE.iter().find(|(a, b, _)| *a == first && *b == second)?;
    char::from_u32(*c as u32)
}

/// The character for two keys typed after the compose key, in either order
/// and either case.
pub fn compose(first: u8, second: u8) -> Option<char> {
    let (a, b) = (first.to_ascii_uppercase(), second.to_ascii_uppercase());
    look_up(first, second).or_else(|| look_up(second, first)).or_else(|| look_up(a, b)).or_else(|| look_up(b, a))
}

/// What a key on a US layout types when Caps Lock means Cyrillic.
pub fn cyrillic(c: char) -> char {
    match c {
        c if (c as u32) < 128 => char::from_u32(CYRILLIC[c as usize] as u32).unwrap_or(c),
        c => c,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compose_in_any_order_and_case() {
        assert_eq!(compose(b'+', b'+'), Some('#'));
        assert_eq!(compose(b'A', b'A'), Some('@'));
        assert_eq!(compose(b'a', b'a'), Some('@'));
        assert_eq!(compose(b'L', b'-'), Some('£'));
        assert_eq!(compose(b'-', b'L'), Some('£'));
        assert_eq!(compose(1, 2), None);
    }

    #[test]
    fn cyrillic_layout() {
        assert_eq!(cyrillic('a'), 'ф');
        assert_eq!(cyrillic('A'), 'Ф');
        assert_eq!(cyrillic('1'), '1');
        assert_eq!(cyrillic('é'), 'é');
    }
}
